"""Rebuild deterministic development-only UI examples from the real analysis engines."""

import json
from pathlib import Path

from redline_core.analyze import analyze_source
from redline_core.conf import Settings
from redline_core.demo import CASES, detector_sample
from redline_core.diagnostics import trace_diagnostics

ROOT = Path(__file__).resolve().parents[1]
SOURCE = """def report():
    events = Event.objects.filter(active=True)
    total = sum(event.duration for event in events)
    selected = [event for event in events if event.duration > 0]
    return total, selected
"""


def main():
    fixtures = []
    for case in CASES:
        trace = detector_sample(case, Settings())
        trace.id = f"demo_{case}"
        trace.started_at = 1_750_000_000
        ids = {span.id: f"demo_{case}_{i}" for i, span in enumerate(trace.spans)}
        for span in trace.spans:
            span.id = ids[span.id]
        for issue in trace.issues:
            issue.span_ids = [ids[sid] for sid in issue.span_ids]
            issue.extra.pop("evidence_span_ids", None)
        data = trace.to_dict(include_profile=False)
        data["profile"] = trace.profile
        data["diagnostics"] = trace_diagnostics(trace)
        fixtures.append(data)
    content = "// Generated by scripts/build_detector_fixtures.py; development-only examples.\n"
    content += "import type { Trace, Speedscope } from '../types'\n"
    content += (
        "export const DETECTOR_SAMPLES: (Trace & { profile: Speedscope | null })[] = "
        + json.dumps(fixtures, indent=2)
        + "\n"
    )
    (ROOT / "frontend/src/mocks/detectorSamples.ts").write_text(content)
    content = "// Shared source example; report generated by scripts/build_detector_fixtures.py.\n"
    content += "export const SOURCE_EXAMPLE = " + json.dumps(SOURCE) + "\n"
    content += "export const SOURCE_REPORT = " + json.dumps(analyze_source(SOURCE), indent=2) + "\n"
    (ROOT / "frontend/src/lib/sourceExample.ts").write_text(content)


if __name__ == "__main__":
    main()
