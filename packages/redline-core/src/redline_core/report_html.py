_CSP = "default-src 'none'; style-src 'unsafe-inline'; img-src data:"


def project_redactor() -> Redactor:
    """A ``Redactor`` with the working directory project's settings (defaults on failure)."""
    from .config import resolve_settings

    try:
        return Redactor(resolve_settings(None, project_root=os.getcwd()).settings)
    except Exception:
        return Redactor()


def _t(redactor: Redactor, value: Any, limit: int = MAX_TEXT) -> str:
    """Redacted, truncated, escaped text."""
    text = "" if value is None else str(value)
    text = redactor.text(text[: limit * 2])
    if len(text) > limit:
        text = text[:limit] + "…"
    return html.escape(text, quote=True)


def _ms(value: float | int | None) -> str:
    return "–" if value is None else f"{float(value):.1f} ms"


def _when(epoch: float | None) -> str:
    if not epoch:
        return "–"
    return time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime(epoch))


def _page(title: str, body: str) -> str:
    return (
        '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
        f'<meta http-equiv="Content-Security-Policy" content="{_CSP}">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>{title}</title><style>{_CSS}</style></head><body>{body}"
        '<p class="meta">Generated by Redline. Bodies, headers and SQL parameters are not '
        "included; secrets are masked.</p></body></html>\n"
    )


def _table(
    headers: Iterable[str], rows: Iterable[Iterable[str]], num: set[int] = frozenset()
) -> str:  # type: ignore[assignment]
    head = "".join(f"<th>{h}</th>" for h in headers)
    body = "".join(
        "<tr>"
        + "".join(
            f'<td class="num">{c}</td>' if i in num else f"<td>{c}</td>" for i, c in enumerate(r)
        )
        + "</tr>"
        for r in rows
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def render_trace(
    trace: Trace, redactor: Redactor | None = None, *, include_sql: bool = False
) -> str:
    """The HTML page for one recording."""
    r = redactor or Redactor()
    label = f"{trace.method} {trace.route or trace.path}"
    pills = "".join(
        f'<span class="pill {html.escape(i.severity)}">{_t(r, i.kind)}</span>'
        for i in trace.issues[:50]
    )
    parts = [
        f"<h1>{_t(r, label)}</h1>",
        f'<div class="meta">Recording <code>{_t(r, trace.id)}</code> · status {int(trace.status)}'
        f" · {_ms(trace.duration_ms)} · {int(trace.query_count)} queries "
        f"({_ms(trace.query_ms)}) · {_when(trace.started_at)}"
        + (f" · release {_t(r, trace.release)}" if trace.release else "")
        + f"</div><div>{pills}</div>",
    ]
    if trace.truncated:
        parts.append(
            "<p>Incomplete: "
            f"{int(trace.truncated.get('dropped_spans', 0))} spans were not stored.</p>"
        )
    if trace.error:
        parts.append(
            f"<h2>Error</h2><p><code>{_t(r, trace.error.get('type') or 'error', 200)}</code></p>"
        )
    parts.append(f"<h2>Issues ({len(trace.issues)})</h2>")
    if trace.issues:
        rows = [
            [
                f'<span class="pill {html.escape(i.severity)}">{_t(r, i.severity)}</span>',
                _t(r, i.kind),
                _t(r, i.title, 300)
                + (f"<br><small>{_t(r, i.detail, 600)}</small>" if i.detail else ""),
                str(int(i.count)),
                _ms(i.total_ms),
                _t(r, i.callsite.location, 300) if i.callsite else "",
            ]
            for i in trace.issues
        ]
        parts.append(_table(["Severity", "Kind", "Issue", "Count", "Time", "Where"], rows, {3, 4}))
    else:
        parts.append("<p>None.</p>")

    total = max(float(trace.duration_ms or 0), 1e-9)
    spans = sorted(trace.spans, key=lambda s: (s.start_ms, s.id))
    rows = []
    for s in spans[:MAX_SPANS]:
        name = s.name
        if s.kind == "sql":
            name = (s.data.get("sql") if include_sql else s.data.get("fingerprint")) or s.name
        left = max(0.0, min(100.0, s.start_ms / total * 100))
        width = max(0.4, min(100.0 - left, s.duration_ms / total * 100))
        rows.append(
            [
                _t(r, s.kind, 40),
                f"<code>{_t(r, name, 600)}</code>",
                _ms(s.start_ms),
                _ms(s.duration_ms),
                f'<div class="bar"><i style="left:{left:.2f}%;width:{width:.2f}%"></i></div>',
            ]
        )
    parts.append(f"<h2>Spans ({len(spans)})</h2>")
    parts.append(_table(["Kind", "Name", "Start", "Duration", ""], rows, {2, 3}))
    if len(spans) > MAX_SPANS:
        parts.append(f"<p>{len(spans) - MAX_SPANS} more spans not shown.</p>")

    sql = [s for s in spans if s.kind == "sql"]
    if sql:
        by_fp: dict[str, list[float]] = {}
        for s in sql:
            key = str(s.data.get("fingerprint") or s.name)
            by_fp.setdefault(key, []).append(s.duration_ms)
        top = sorted(by_fp.items(), key=lambda kv: (-sum(kv[1]), kv[0]))[:20]
        parts.append("<h2>SQL by statement</h2>")
        parts.append(
            _table(
                ["Statement", "Runs", "Total"],
                [[f"<code>{_t(r, k, 600)}</code>", str(len(v)), _ms(sum(v))] for k, v in top],
                {1, 2},
            )
        )
    if trace.logs:
        parts.append(f"<h2>Logs ({len(trace.logs)})</h2>")
        parts.append(
            _table(
                ["t", "Level", "Logger", "Message"],
                [
                    [
                        _ms(lg.t_ms),
                        _t(r, lg.level, 20),
                        _t(r, lg.logger, 100),
                        _t(r, lg.message, 500),
                    ]
                    for lg in trace.logs[:200]
                ],
                {0},
            )
        )
    return _page(_t(r, label, 200) + " – Redline", "".join(parts))


def load_run(reader: Any, run_id: str) -> Run | None:
    """A load run through a read-only ``TraceReader`` connection (no writes, no reaping)."""
    from .storage.sqlite import _run, _run_step

    try:
        rows = reader._query("SELECT * FROM runs WHERE id = ?", (run_id,))
    except Exception:
        return None
    if not rows:
        return None
    steps = reader._query("SELECT * FROM run_steps WHERE run_id = ? ORDER BY step", (run_id,))
    return _run(rows[0], [_run_step(s) for s in steps])


def render_run(run: Run, redactor: Redactor | None = None) -> str:
    """The HTML page for one load run."""
    r = redactor or Redactor()
    d = run.to_dict()

    def dash(value: Any) -> Any:
        return "–" if value is None else value

    summary = d["summary"]
    parts = [
        f"<h1>{_t(r, run.name or 'Load run', 200)}</h1>",
        f'<div class="meta">Run <code>{_t(r, run.id)}</code> · {_t(r, run.status, 20)} · '
        f"{_when(run.created_at)}</div>",
        f"<p>Verdict: {_t(r, dash(summary.get('verdict')), 200)} · knee step: "
        f"{_t(r, dash(summary.get('knee_step')), 20)} · "
        f"max OK rate: {_t(r, dash(summary.get('max_ok_rps')), 20)} rps</p>",
        "<h2>Steps</h2>",
        _table(
            ["Step", "Target rps", "Achieved", "Sent", "OK", "Errors", "p50", "p95", "p99", "Max"],
            [
                [
                    str(s["step"]),
                    f"{s['target_rps']:g}",
                    f"{s['achieved_rps']:g}",
                    str(s["sent"]),
                    str(s["ok"]),
                    str(s["errors"]),
                    _ms(s["p50_ms"]),
                    _ms(s["p95_ms"]),
                    _ms(s["p99_ms"]),
                    _ms(s["max_ms"]),
                ]
                for s in d["steps"]
            ],
            set(range(10)),
        ),
    ]
    errors = [(k, v) for s in d["steps"] for k, v in s["error_breakdown"].items()]
    if errors:
        totals: dict[str, int] = {}
        for k, v in errors:
            totals[k] = totals.get(k, 0) + int(v)
        parts.append("<h2>Errors</h2>")
        parts.append(
            _table(
                ["Kind", "Count"],
                [[_t(r, k, 100), str(v)] for k, v in sorted(totals.items())],
                {1},
            )
        )
    reqs = (run.config or {}).get("requests") or []
    if isinstance(reqs, list) and reqs:
        parts.append("<h2>Scenario requests</h2>")
        parts.append(
            _table(
                ["Method", "Path"],
                [
                    [_t(r, q.get("method", "GET"), 10), f"<code>{_t(r, q.get('path'), 300)}</code>"]
                    for q in reqs[:100]
                    if isinstance(q, dict)
                ],
            )
        )
    return _page(_t(r, run.name or "Load run", 200) + " – Redline", "".join(parts))
