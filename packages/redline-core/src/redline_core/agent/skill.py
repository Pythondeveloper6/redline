"""Text that teaches a coding agent to use redline: a Claude skill and an AGENTS.md section."""

from __future__ import annotations

from pathlib import Path
from typing import Any

__all__ = ["agents_text", "skill_text"]

_BODY = """\
# Working with redline

Redline records real requests and finds performance problems (N+1 queries, slow or repeated
queries, blocking calls, large results, slow external or LLM calls). Use its data instead of
guessing.

## Find problems

- `redline mcp --store .redline/redline.db` serves read-only tools over MCP: `list_issues`,
  `explain_issue`, `get_trace`, `instrumentation_report`, `verify_fix`, `llm_summary`.
- Without MCP: `redline fix-prompt ISSUE_ID --store .redline/redline.db` writes a brief for one
  finding. `redline instrumentation --store ...` says what redline cannot see.
- Findings are ranked by *sampled* observed time. Costs overlap; never add them up as savings.

## Fix a problem

1. Record a baseline before editing: `redline check record check.toml`.
2. Make the smallest change at the reported callsite. Keep every response identical.
3. Compare: `redline check compare check.toml --json report.json`.
4. Confirm: `redline check verify report.json --kind KIND`. Only `finding: gone` with
   responses `equal` means fixed. `inconclusive` means collect more samples, not success.
5. In CI, `redline check findings report.json --new-only` lists findings new in this change.

## Add redline to an app

- FastAPI: `from fastapi_redline import install_if_dev; install_if_dev(app, engine=engine)`.
- Django: add `django_redline` to `INSTALLED_APPS` and its middleware (see the Django guide).
- Flask / Litestar: `flask_redline.install(app)` / `litestar_redline` plugin.
- Optional LLM-call spans: `instrument_anthropic()` / `instrument_openai()` (token counts and
  timing only; prompt text is never stored).

## Rules

- Never capture, log or paste prompt or completion text, tokens, passwords or request bodies.
- Never delete traces or run EXPLAIN ANALYZE on a production store.
- Do not weaken a test, threshold or budget to make a finding disappear.
- Do not push, tag or publish without the owner's explicit approval.
- `redline diagnose` only previews unless the owner has enabled `ai_diagnosis` and set a key;
  never enable it or set the key yourself.
"""


def skill_text() -> str:
    return (
        "---\nname: redline\n"
        "description: Find and fix backend performance problems with redline's recorded "
        "traces: N+1 queries, slow queries, blocking calls, slow LLM or external calls. "
        "Use when asked to speed up an endpoint, review a PR for performance, or verify a fix.\n"
        "---\n\n" + _BODY
    )


def agents_text() -> str:
    return (
        "<!-- redline: begin (generated by `redline agent-skill`) -->\n"
        + _BODY
        + ("<!-- redline: end -->\n")
    )


def configure(parser: Any) -> None:
    parser.add_argument(
        "--format", choices=("skill", "agents"), default="skill", help="SKILL.md or AGENTS section"
    )
    parser.add_argument("--write", metavar="DIR", help="write into DIR instead of printing")
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")


def command(args: Any, out: Any, err: Any) -> int:
    text = skill_text() if args.format == "skill" else agents_text()
    if not args.write:
        out.write(text)
        return 0
    root = Path(args.write)
    target = root / "redline" / "SKILL.md" if args.format == "skill" else root / "AGENTS.redline.md"
    if target.exists() and not args.force:
        err.write(f"redline agent-skill: {target} exists; use --force to overwrite\n")
        return 2
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    out.write(f"wrote {target}\n")
    return 0
